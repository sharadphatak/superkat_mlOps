"""Verified model loading and normalized inference shared by app and tests."""
import json
from pathlib import Path
import joblib
import numpy as np
from src.common import canonical_features, fingerprint, versions


def load_bundle(directory="models"):
    directory = Path(directory)
    meta = json.loads((directory / "metadata.json").read_text())
    if fingerprint(directory / "model.joblib") != meta["model_sha256"]:
        raise RuntimeError("Model hash mismatch; model and metadata must be published together")
    current = versions()
    mismatch = {p: (v, current[p]) for p, v in meta["packages"].items() if current[p] != v}
    if mismatch:
        raise RuntimeError(f"Training/deployment package mismatch: {mismatch}. Install locked requirements.")
    # Only load the trusted model generated by this repository, never user-uploaded pickle.
    return joblib.load(directory / "model.joblib"), meta


def predict_frame(model, frame):
    result = model.predict(canonical_features(frame))
    if not np.isfinite(result).all():
        raise RuntimeError("Non-finite prediction")
    return result
